# -- население ----------------------------------------------------------------
#
# Заказчик задал численность по островам и по крупным городам; малые пункты
# описаны одной фразой — «не более 15 тыс.», без отдельных цифр на каждый.
# Поэтому здесь хранится ровно то, что задано, а размер конкретного округа
# выводится из этого на лету (`district_population`): выдумывать каждому селу
# свою цифру не из чего, а хранить выведенное — значит однажды разойтись с
# исходными числами.
#
# Нужно это выборам: доля голосов по стране сводится из округов с весом по
# населению, а не по мандатам. Мандаты по островам разложены неровно — на
# Вакуле выходит около 6 тыс. человек на мандат, на Каспиане около 9,4 тыс., —
# и считать по мандатам значило бы дать западному избирателю в полтора раза
# больше веса, чем центральному.

#: Сколько человек живёт на каждом острове. Ключ — подпись острова из
#: `ISLANDS`, сумма по всем — миллион, население Конфедерации.
ISLAND_POPULATION: dict[str, int] = {
    "Остров Вакула (запад)": 180_000,
    "Остров Каспиан (центр)": 450_000,
    "Остров Виделлиус (восток)": 350_000,
    "Остров Нурик (юг)": 20_000,
}

#: Метрополии и их население. Остальные жители острова расходятся по сёлам.
#:
#: Саттмалвик — единственное число, которого заказчик не назвал: по острову
#: дан только итог в 180 тыс. Взято по доле города в мандатах острова (13 из
#: 30, это около 78 тыс.) и округлено до 80 тыс. — тогда на десять сёл Вакулы
#: приходится ровно по 10 тыс., что укладывается в заданное «не более 15».
#: Если настоящая цифра другая, править нужно только эту строку.
CITY_POPULATION: dict[str, int] = {
    "Саттмалвик": 80_000,
    "Гаффинсвик": 300_000,
    "Триединсборг": 70_000,
    "Нивенсхолл": 160_000,
}

#: Население Конфедерации — сумма островов.
TOTAL_POPULATION = sum(ISLAND_POPULATION.values())


def _island_of_code(code: int) -> str:
    for c, _name, _seats, region, _places in SEED_DISTRICTS:
        if c == code:
            return island_of(region)
    return ""


def village_population(island: str) -> float:
    """Сколько человек в одном селе этого острова.

    Малые пункты заданы одной планкой на всех — «не более 15 тыс.», — и
    различать их между собой не по чему. Поэтому остаток острова (всё, что
    не пришлось на метрополии) делится между сёлами поровну.
    """
    people = ISLAND_POPULATION.get(island, 0) - sum(
        size for region, size in CITY_POPULATION.items()
        if island_of(region) == island)
    villages = sum(
        len(places) for _c, _n, _s, region, places in SEED_DISTRICTS
        if places is not CITY and island_of(region) == island)
    return people / villages if villages else 0.0


def district_population(code: int) -> float:
    """Сколько человек в округе — по данным карты, а не по проекту.

    Округ города получает долю метрополии по своим мандатам: как поделено
    население Гаффинсвика между пятью его районами, заказчик не уточнял, а
    районы нарезаны примерно по людям — это и берём. Сельский округ получает
    столько сёл, сколько их в нём числится на карте.

    Ноль — округ, которого на карте нет: у проектов, начатых до её появления,
    номеров не было вовсе.
    """
    island = _island_of_code(code)
    if not island:
        return 0.0

    for c, _name, seats, region, places in SEED_DISTRICTS:
        if c != code:
            continue
        if places is CITY:
            city = CITY_POPULATION.get(region, 0)
            share = sum(s for _c2, _n2, s, r2, p2 in SEED_DISTRICTS
                        if p2 is CITY and r2 == region)
            return city * seats / share if share else 0.0
        return len(places) * village_population(island)
    return 0.0


def is_city(code: int) -> bool:
    """Городской ли это округ — то есть сам себе населённый пункт."""
    return next((places is CITY for c, _n, _s, _r, places in SEED_DISTRICTS
                 if c == code), False)


def island_of(region: str) -> str:
    """Остров, на котором стоит метрополия округа — подпись для списков."""
    return ISLANDS.get(region, region)


def islands() -> list[str]:
    """Острова архипелага по порядку первого появления на карте.

    Нивенсхолл и Триединсборг делят один остров Виделлиус, поэтому островов
    меньше, чем регионов, — список для строк «сдвиг по острову» на экране
    выборов, а не для группировки одних лишь округов.
    """
    seen: list[str] = []
    for _code, _name, _seats, region, _places in SEED_DISTRICTS:
        island = island_of(region)
        if island not in seen:
            seen.append(island)
    return seen


def city_regions() -> list[str]:
    """Метрополии, у которых есть городские округа — по первому появлению.

    Городской округ не хранит очков поддержки сам: они общие на весь город
    — один запас на все его округа (Саттмалвик-порт и -центр делят один
    и тот же «Саттмалвик», а не два отдельных). Список городов — это и
    есть список таких метрополий, а не список округов.
    """
    seen: list[str] = []
    for _code, _name, _seats, region, places in SEED_DISTRICTS:
        if places is CITY and region not in seen:
            seen.append(region)
    return seen
