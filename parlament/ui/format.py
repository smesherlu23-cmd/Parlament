"""Форматирование строк интерфейса: склонения, проценты."""

from __future__ import annotations

SEATS = ["место", "места", "мест"]
#: В зале — места, на карте — мандаты: одно и то же число, но в
#: разговоре про округа и острова «мест» звучит не про то.
MANDATES = ["мандат", "мандата", "мандатов"]
#: После «из» нужен родительный падеж: «из 1 мандата», «из 2 мандатов».
MANDATES_OF = ["мандата", "мандатов", "мандатов"]
PARTIES = ["партия", "партии", "партий"]
CONVOCATIONS = ["созыве", "созывах", "созывах"]
PARTIES_COUNT = ["партия", "партии", "партий"]
DISTRICTS = ["округ", "округа", "округов"]
SETTLEMENTS = ["населённый пункт", "населённых пункта", "населённых пунктов"]
#: Короткая форма — там, где «населённых пунктов» не влезает: в строке
#: партии в диалоге выгрузки и в углу самой картинки.
PLACES = ["пункт", "пункта", "пунктов"]
PLACES_IN = ["пункте", "пунктах", "пунктах"]
CITIES = ["город", "города", "городов"]


def plural(count: int, forms: list[str]) -> str:
    """Форма существительного при числе: 1 место, 2 места, 5 мест."""
    n = abs(count) % 100
    if 11 <= n <= 19:
        return forms[2]
    last = n % 10
    if last == 1:
        return forms[0]
    if 2 <= last <= 4:
        return forms[1]
    return forms[2]


def pluralize(count: int, forms: list[str]) -> str:
    """«5 мест» — число вместе со склонённым словом."""
    return f"{count} {plural(count, forms)}"


def people(value: float) -> str:
    """«180 тыс.» — население округа или острова.

    Точное число человек здесь не нужно ни разу: население расписано по
    островам крупными долями (см. `district_seed`), и «179 640» создавало бы
    видимость точности, которой в игре нет.
    """
    return f"{round(value / 1000):d} тыс."


def count(value: float) -> str:
    """«6 207» — число с пробелом между тысячами, как принято по-русски."""
    return f"{round(value):,}".replace(",", "\u00a0")


def share(value: float) -> str:
    """«28,3 %» — из готовой доли, а не из отношения двух чисел.

    Отличается от `percent` тем, что доля уже посчитана: голоса по стране
    сводятся из округов со своими весами, и делением одного числа на другое
    их не получить.
    """
    return f"{value:.1f}".replace(".", ",") + " %"


def percent(value: int, total: int) -> str:
    """«28,3 %» — с запятой, как принято в русской типографике."""
    if not total:
        return "0,0 %"
    return f"{value / total * 100:.1f}".replace(".", ",") + " %"
