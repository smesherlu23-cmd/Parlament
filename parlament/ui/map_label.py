"""Размер цифры на округе — общий расчёт для окна и для выгрузки в PNG.

Держим в одном месте, потому что карта рисуется дважды разными средствами
(холст Flet и Pillow), а выглядеть должна одинаково.
"""

from __future__ import annotations

from ..district_geometry import DISTRICT_LABEL_ROOM

#: Мельче этого подпись не читается: такой округ остаётся без цифры, число
#: мест по нему покажет разбор по клику.
MIN_LABEL_SIZE = 6


def label_size(code: int, base: float, map_width: float, text: str) -> float:
    """Насколько крупной может быть подпись округа, чтобы в него влезть.

    Городские округа занимают на карте несколько пикселей: цифра обычного
    размера вылезала за их границы и накрывала соседей — прочитать нельзя
    было ни одну.

    `DISTRICT_LABEL_ROOM` — радиус свободного места вокруг точки подписи в
    долях ширины карты. Двузначное число шире однозначного, поэтому в
    знаменателе длина текста: «10» на том же пятачке должно быть мельче,
    чем «4».
    """
    room = DISTRICT_LABEL_ROOM.get(code)
    if room is None:
        return base
    fits = 2 * room * map_width / (0.75 * max(1, len(text)) + 0.6)
    return min(base, fits)
