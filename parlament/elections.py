"""Расчёт выборов: как голоса в округе превращаются в места.

Правило игры (по уточнению заказчика): места округа делятся между партиями
в процентном соотношении набранных голосов, кто набрал больше — забирает
большинство мест округа. Если борьбы не было (голоса есть только у одной
партии), победитель забирает все места округа — это получается само собой,
отдельной ветки в коде не требует.

Способ деления — метод наибольших остатков (квота Хэйра): каждой партии
достаётся целая часть от её доли, а оставшиеся места уходят тем, у кого
самый большой дробный хвост. Из распространённых методов он ближе всех к
буквальному «в процентном соотношении»: Д'Ондт, например, системно
подсуживает крупным партиям и от чистых процентов заметно отклоняется.
"""

from __future__ import annotations

from dataclasses import dataclass, replace

#: Ничьи (одинаковые остатки, одинаковые голоса) разрешаются по порядку
#: партий во входном словаре — то есть по порядку справочника, раз вызывающая
#: сторона строит `votes` из него. Брать «последним доводом» id партии нельзя:
#: id случайный, и победитель ничьей выглядел бы взятым с потолка.


def allocate_seats(votes: dict[str, float], seats: int) -> dict[str, int]:
    """Делит `seats` мест округа между партиями пропорционально голосам.

    :param votes: вес партий в округе — `{party_id: число}`. Это доля голосов
                  партии (см. `PartyResult.share`), уже без тех, кто не
                  прошёл барьер; дробные значения допустимы. Нули и минусы
                  игнорируются: партия без голосов мест не получает.
    :param seats: сколько мест разыгрывается в округе.
    :return: `{party_id: места}` — только партии, получившие хотя бы одно
             место. Сумма всегда ровно `seats`, если голоса вообще есть.

    Пустой ввод (ни одного голоса) даёт пустой результат: места округа
    остаются нераспределёнными, а не раздаются наугад.
    """
    if seats <= 0:
        return {}

    # Дроби не округляем: доля голосов после нормировки и колебания почти
    # никогда не бывает целой. Округление здесь съедало бы как раз ту
    # разницу, ради которой доля и считается.
    clean = {pid: float(v) for pid, v in votes.items() if float(v) > 0}
    total = sum(clean.values())
    if not clean or total <= 0:
        return {}

    # Целая часть доли — гарантированные места.
    exact = {pid: v * seats / total for pid, v in clean.items()}
    result = {pid: int(share) for pid, share in exact.items()}

    # Остаток раздаём по величине дробного хвоста: сначала самый длинный.
    left = seats - sum(result.values())
    if left > 0:
        rank = _register_rank(clean)
        order = sorted(
            clean,
            key=lambda pid: (exact[pid] - int(exact[pid]), clean[pid], rank[pid]),
            reverse=True,
        )
        for pid in order[:left]:
            result[pid] += 1

    return {pid: n for pid, n in result.items() if n > 0}


def _register_rank(votes: dict[str, float]) -> dict[str, float]:
    """Вес партии при ничьей: чем раньше в справочнике, тем больше.

    Сортировки ниже идут по убыванию, поэтому первая партия должна получить
    наибольшее число — берём позицию с минусом.
    """
    return {pid: -index for index, pid in enumerate(votes)}


def district_winner(votes: dict[str, float], seats: int) -> str | None:
    """Партия, которой достаётся округ, — по местам, а при равенстве по голосам.

    Именно её цветом красится округ на карте. `None`, если по округу
    ещё нет данных.
    """
    allocation = allocate_seats(votes, seats)
    if not allocation:
        return None
    # Дроби не округляем — см. `allocate_seats`.
    clean = {pid: float(v) for pid, v in votes.items() if float(v) > 0}
    rank = _register_rank(clean)
    return max(allocation, key=lambda pid: (allocation[pid], clean.get(pid, 0), rank[pid]))


def allocate_all(
    votes_by_district: dict[str, dict[str, int]],
    district_seats: dict[str, int],
) -> dict[str, dict[str, int]]:
    """Считает места по всем округам разом: `{district_id: {party_id: места}}`."""
    return {
        district_id: allocate_seats(votes, district_seats.get(district_id, 0))
        for district_id, votes in votes_by_district.items()
        if district_id in district_seats
    }


def totals_by_party(allocation: dict[str, dict[str, int]]) -> dict[str, int]:
    """Сводит места всех округов в общий состав парламента."""
    totals: dict[str, int] = {}
    for per_party in allocation.values():
        for party_id, seats in per_party.items():
            totals[party_id] = totals.get(party_id, 0) + seats
    return totals


# -- доли голосов и случайные колебания --------------------------------------
#
# Голоса в округе не вводятся руками, а считаются: у каждой партии есть база —
# её доля от всего запаса очков округа, а не только от розданных, — и к ней
# прибавляются (в процентных пунктах) настроение по стране, сдвиг по острову
# и местный модификатор, а затем небольшое случайное колебание — события
# последних дней кампании, а не бросок кубика. Итоговые доли нормируются к
# 100 % и уже потом делятся на места.
#
# Неразобранные очки — это люди, к которым ни одна партия не пришла: они
# делятся поровну между всеми, см. `base_shares`. Без этого одно очко из
# шести давало бы те же 100 %, что и все шесть.

#: Сколько очков неформальной популярности несёт обычный населённый пункт.
#: Эти очки игроки делят между партиями, отсюда и берётся база голосов.
SETTLEMENT_SUPPORT = 6

#: Городской округ — сам себе населённый пункт, и запас очков в нём вдвое
#: больше: город многолюднее деревни, и делить в нём есть что.
CITY_SUPPORT = 12

#: Случайное колебание — не бросок, а погрешность неопределившихся и
#: последних дней кампании. Треугольное распределение вокруг нуля: большой
#: сюрприз редкость, как и в жизни, а не один из равновероятных исходов.
WOBBLE_RANGE = 3.0

#: Явный барьер: меньше этой доли голосов в округе — место не достаётся,
#: даже по остатку. Сам процент в разборе всё равно виден — это не запрет
#: участвовать, а условие реального попадания в состав.
THRESHOLD_PERCENT = 5.0


@dataclass(frozen=True)
class PartyResult:
    """Расклад одной партии в одном округе — с разбивкой по слагаемым.

    Хранится целиком, а не одной долей: ведущему нужно видеть, из чего
    сложился результат — база, поправки, колебание, — а пересчитать это
    потом будет не из чего: колебание случайно и не повторяется.

    Все поля, кроме `share`, — в процентных пунктах и до нормировки; их
    сумма может не совпадать с `share` буквально (см. `normalize_shares`).
    """

    #: Доля партии от всего запаса очков округа — её организованная база
    #: вместе с долей неопределившихся, которые достались ей при равном
    #: делении (см. `base_shares`). Партия, не работавшая в округе вовсе,
    #: получает не ноль, а свою часть неопределившихся: у них организации
    #: нет ни у кого.
    base: float = 0.0
    #: «Настроение по стране» — свободная поправка, одна на партию сразу
    #: для всех округов: волна за или против неё по всей карте, а не
    #: точечная правка в одном округе.
    national: float = 0.0
    #: Сдвиг по острову — то же самое, но на один остров архипелага, а не
    #: на всю карту и не на один округ: соседние округа острова обычно
    #: голосуют похоже.
    island: float = 0.0
    #: Свободный модификатор на конкретный округ, который выставляет
    #: ведущий руками — любое число, отрицательное действует как штраф.
    #: Причина не задана нарочно: дебаты, скандал, что угодно по ходу
    #: партии.
    modifier: float = 0.0
    #: Случайное колебание — не бросок, а погрешность неопределившихся и
    #: последних дней кампании, см. `WOBBLE_RANGE`.
    wobble: float = 0.0
    #: Итоговая доля голосов в округе, в процентах, уже после того как
    #: отрицательные суммы обнулились и все доли округа нормировались к
    #: 100 % — то, что реально идёт на места. Ниже `THRESHOLD_PERCENT` мест
    #: не будет, но доля всё равно показывается как есть.
    share: float = 0.0

    @property
    def raw(self) -> float:
        """Сумма слагаемых до нормировки — то, что показывает разбор."""
        return self.base + self.national + self.island + self.modifier + self.wobble

    def to_dict(self) -> dict:
        return {"base": self.base, "national": self.national, "island": self.island,
                "modifier": self.modifier, "wobble": self.wobble, "share": self.share}

    @staticmethod
    def from_dict(raw: dict) -> "PartyResult":
        def number(value, default=0.0):
            try:
                return float(value)
            except (TypeError, ValueError):
                return default
        return PartyResult(
            base=number(raw.get("base"), 0.0),
            national=number(raw.get("national"), 0.0),
            island=number(raw.get("island"), 0.0),
            modifier=number(raw.get("modifier"), 0.0),
            wobble=number(raw.get("wobble"), 0.0),
            share=number(raw.get("share"), 0.0),
        )


def base_shares(points: dict[str, float], capacity: float = 0.0) -> dict[str, float]:
    """База каждой партии — её доля голосов округа до поправок, в процентах.

    :param points: очки поддержки партий, `{party_id: очки}`.
    :param capacity: сколько очков в округе можно было раздать всего.

    Считается не от розданных очков, а от всего запаса. Очки, которые никто
    не разобрал, — это неопределившиеся: люди, к которым ни одна партия не
    пришла. В день голосования они расходятся поровну между всеми, потому
    что организации у них нет ни у кого.

    Без запаса выходила бессмыслица: одно очко из шести давало ровно те же
    100 %, что и все шесть. Деревня, где единственная партия завела одного
    сторонника, доставалась ей целиком — при том что пятерых из шести там
    не убедил никто. Теперь одно очко из шести даёт заметный перевес
    (44 % против 28 % при трёх партиях), но не разгром, а полностью
    разобранный пункт по-прежнему уходит целиком.

    Запас, равный нулю (округ без пунктов — такое бывает у проектов,
    начатых до карты), возвращает к прежнему счёту от розданного: считать
    там не от чего.
    """
    if not points:
        return {}
    count = len(points)
    given = sum(max(0.0, v) for v in points.values())

    # Знаменатель — весь запас округа; если очков почему-то роздали больше
    # (файл правили руками), считаем от розданного, чтобы доли не ушли за
    # сотню. В обоих случаях сумма долей ровно 100 %.
    total = max(given, float(capacity))
    if total <= 0:
        equal = 100.0 / count
        return {pid: equal for pid in points}

    undecided = (total - given) / count
    return {pid: (max(0.0, v) + undecided) / total * 100.0
            for pid, v in points.items()}


def roll_wobble(rng) -> float:
    """Случайное колебание, ±`WOBBLE_RANGE` процентных пунктов.

    Треугольное распределение с вершиной на нуле: небольшой разброс —
    обычное дело (неопределившиеся, погода в день голосования), а вот
    качнуть округ на все три пункта разом — редкость.

    `rng` передаётся снаружи, чтобы тесты были повторяемы.
    """
    return rng.triangular(-WOBBLE_RANGE, WOBBLE_RANGE, 0.0)


def normalize_shares(raw: dict[str, float]) -> dict[str, float]:
    """Приводит сырые доли (с учётом всех поправок) к сумме 100 %.

    Отрицательные суммы (модификатор увёл партию в минус) обнуляются перед
    нормировкой — как и раньше, партия без голосов не должна вычитать их
    у остальных. Если в минус ушли все, доли остаются нулевыми: делить
    нечего.
    """
    clamped = {pid: max(0.0, v) for pid, v in raw.items()}
    total = sum(clamped.values())
    if total <= 0:
        return {pid: 0.0 for pid in clamped}
    return {pid: v / total * 100.0 for pid, v in clamped.items()}


def renormalize(results: dict[str, PartyResult]) -> dict[str, PartyResult]:
    """Пересчитывает доли округа после того, как из него убрали партию.

    Слагаемые (база, поправки, колебание) — то, что было разыграно, и их не
    трогаем: переписывать бросок задним числом нельзя. Меняются только доли:
    голоса ушедшей партии расходятся между оставшимися пропорционально их
    собственным весам, и округ снова даёт в сумме 100 %.

    Без этого разбор округа показывал бы доли, не сходящиеся к сотне («16,9 %
    и все пять мест»), а барьер остался бы посчитанным по старому раскладу —
    партия, которую соперник держал ниже пяти процентов, так и не получила бы
    мест после его исчезновения.
    """
    share = normalize_shares({party_id: r.raw for party_id, r in results.items()})
    return {party_id: replace(r, share=share[party_id])
            for party_id, r in results.items()}


def weights(results: dict[str, PartyResult]) -> dict[str, float]:
    """Доли, которые реально идут на места — только партии выше барьера.

    Барьер режет по доле округа, а не по абсолютному числу: с ним места не
    достаются шумовым долям процента, даже если по остатку что-то бы да
    причиталось.
    """
    return {party_id: r.share for party_id, r in results.items()
            if r.share >= THRESHOLD_PERCENT}


def shares(results: dict[str, PartyResult]) -> dict[str, float]:
    """Все доли голосов округа — включая тех, кто не прошёл барьер.

    Именно все: барьер запрещает места, а не сам процент — его в разборе
    видно и у партий, что его не преодолели.
    """
    return {party_id: r.share for party_id, r in results.items() if r.share > 0}
